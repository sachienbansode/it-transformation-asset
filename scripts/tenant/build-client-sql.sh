#!/usr/bin/env bash
# ITH-121 — build db/new_client_database.sql: ONE file that creates a complete, empty IT Hub client database
# (all tables + the default system configuration, no people and no business data). Rebuilt for every release.
#
#   bash scripts/tenant/build-client-sql.sh            # needs a PostgreSQL server reachable with the current PG* variables
#
# How: creates a temporary database, runs db/01_schema.sql + every migration (05..NN) exactly as deploy.sh does for a
# blank client, adds the KPI defaults the app would add on first start, clears the migration audit noise, dumps it
# (no owners / grants, so it loads on any server), then drops the temporary database.
set -euo pipefail
cd "$(dirname "$0")/../.."
TMP="ithub_build_$$"; OUT="db/new_client_database.sql"; VERSION="$(cat VERSION 2>/dev/null || echo unknown)"
P() { psql -X -q -v ON_ERROR_STOP=1 "$@"; }
P -d postgres -c "CREATE DATABASE $TMP" >/dev/null
trap 'P -d postgres -c "DROP DATABASE IF EXISTS $TMP" >/dev/null 2>&1 || true' EXIT
P -d "$TMP" -f db/01_schema.sql >/dev/null
P -d "$TMP" -c "INSERT INTO settings (key, value, description) VALUES ('tenant.profile', '\"blank\"', 'Client instance: nothing pre-loaded')" >/dev/null
for f in $(ls db/[0-9][0-9]_*.sql | sort); do
  n=$(basename "$f"); num=${n%%_*}
  [[ 10#$num -lt 5 ]] && continue
  [[ "$n" =~ clear|reset ]] && continue
  P -d "$TMP" -c "SET client_min_messages=warning; SET search_path TO public" -f "$f" >/dev/null
done
P -d "$TMP" <<'SQL' >/dev/null
-- KPI module defaults (the app adds the same on first start when empty)
INSERT INTO kpi_categories (name, description, color, sort_order)
SELECT * FROM (VALUES ('Run', 'Keep the lights on — operations & maintenance', '#2563eb', 1), ('Change', 'Incremental improvements & projects', '#d97706', 2),
  ('Transform', 'Strategic & innovation initiatives', '#9333ea', 3)) v(n, d, c, s) WHERE NOT EXISTS (SELECT 1 FROM kpi_categories);
INSERT INTO kpi_settings (approval_enabled, scoring_model, default_weightage_type, allow_cto_override)
SELECT false, 'percentage', 'equal', true WHERE NOT EXISTS (SELECT 1 FROM kpi_settings);
-- a new client starts with no deployment history (deploy.sh records the first one)
TRUNCATE schema_migrations, app_deployments RESTART IDENTITY;
SQL
{
  echo "-- IT Hub $VERSION — complete EMPTY client database: all tables + default system configuration."
  echo "-- No users, no business data. Generated by scripts/tenant/build-client-sql.sh on $(date -u +%F)."
  echo "-- Used by scripts/tenant/new-tenant.sh. Load into an EMPTY database only:  psql -d <new_db> -v ON_ERROR_STOP=1 -f db/new_client_database.sql"
  echo "-- After loading, run deploy.sh in the client's folder (it records the version and applies any newer scripts)."
  echo
  pg_dump -d "$TMP" --no-owner --no-privileges --no-comments | grep -v '^-- Dumped \(from\|by\)' | grep -v '^SET transaction_timeout' | sed '/^\\restrict\|^\\unrestrict/d'
} > "$OUT"
echo "Built $OUT ($(wc -c < "$OUT") bytes) for version $VERSION"
